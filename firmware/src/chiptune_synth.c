bool chiptune_synth_render_sample(float *out_sample) {
    bool produced = false;
    float sample = 0.0f;

    // 1. Chiptune melody playback
    if (active_chiptune_track >= 0) {
        const chiptune_track_t *trk = &CHIPTUNE_TRACKS[active_chiptune_track];
        if (chiptune_note_samples_left == 0) {
            chiptune_step++;
            if (chiptune_step < trk->count) {
                float f = trk->notes[chiptune_step].freq;
                uint32_t dur = trk->notes[chiptune_step].dur_ms;
                chiptune_current_freq = f;
                live_chiptune_freq = f;
                chiptune_amplitude = calc_amp(f);
                uint32_t tot = (dur * AUDIO_SAMPLE_RATE) / 1000;
                chiptune_note_samples_left = tot;
                chiptune_sound_samples_left = (f > 0.0f) ? ((tot * 94) / 100) : 0;
                chiptune_note_sample_idx = 0;
                chiptune_phase_step = (f > 0.0f) ? (f * 2.0f * 3.14159265f / (float)AUDIO_SAMPLE_RATE) : 0.0f;
            } else {
                active_chiptune_track = -1;
                chiptune_current_freq = 0.0f;
                live_chiptune_freq = 0.0f;
                chiptune_phase_step = 0.0f;
            }
        }

        if (active_chiptune_track >= 0) {
            if (chiptune_note_samples_left > 0) {
                chiptune_note_samples_left--;
            }

            if (chiptune_note_sample_idx < chiptune_sound_samples_left && chiptune_current_freq > 0.0f) {
                float env = 1.0f;
                if (chiptune_note_sample_idx < 32) {
                    env = (float)chiptune_note_sample_idx / 32.0f;
                }
                uint32_t rem = chiptune_sound_samples_left - chiptune_note_sample_idx;
                if (rem < 32) {
                    float r_env = (float)rem / 32.0f;
                    if (r_env < env) env = r_env;
                }

                float s1 = sinf(chiptune_phase);
                float s3 = sinf(chiptune_phase * 3.0f);
                float s5 = sinf(chiptune_phase * 5.0f);
                float warm_wave = 0.65f * s1 + 0.25f * s3 + 0.10f * s5;

                sample += warm_wave * (chiptune_amplitude * env);
                chiptune_note_sample_idx++;
                produced = true;
            }

            chiptune_phase += chiptune_phase_step;
            if (chiptune_phase >= 2.0f * 3.14159265f) {
                chiptune_phase -= 2.0f * 3.14159265f;
            }
        }
    }

    // 2. Cosmic SFX playback
    if (active_cosmic_sfx >= 0) {
        const chiptune_track_t *trk = &COSMIC_SFX_TRACKS[active_cosmic_sfx];
        if (sfx_note_samples_left == 0) {
            cosmic_sfx_step++;
            if (cosmic_sfx_step < trk->count) {
                float f = trk->notes[cosmic_sfx_step].freq;
                uint32_t dur = trk->notes[cosmic_sfx_step].dur_ms;
                sfx_current_freq = f;
                live_chiptune_freq = f;
                sfx_amplitude = calc_amp(f);
                uint32_t tot = (dur * AUDIO_SAMPLE_RATE) / 1000;
                sfx_note_samples_left = tot;
                sfx_sound_samples_left = tot;
                sfx_note_sample_idx = 0;
                sfx_phase_step = (f > 0.0f) ? (f * 2.0f * 3.14159265f / (float)AUDIO_SAMPLE_RATE) : 0.0f;
            } else {
                active_cosmic_sfx = -1;
                sfx_current_freq = 0.0f;
                live_chiptune_freq = 0.0f;
                sfx_phase_step = 0.0f;
            }
        }

        if (active_cosmic_sfx >= 0) {
            if (sfx_note_samples_left > 0) {
                sfx_note_samples_left--;
            }

            if (sfx_note_sample_idx < sfx_sound_samples_left && sfx_current_freq > 0.0f) {
                const uint32_t RAMP_SAMPLES = 192;
                float env = 1.0f;
                if (sfx_note_sample_idx < RAMP_SAMPLES && sfx_sound_samples_left > RAMP_SAMPLES * 2) {
                    float x = (float)sfx_note_sample_idx / (float)RAMP_SAMPLES;
                    env = 0.5f * (1.0f - cosf(3.14159265f * x));
                }
                uint32_t remaining = sfx_sound_samples_left - sfx_note_sample_idx;
                if (remaining < RAMP_SAMPLES && sfx_sound_samples_left > RAMP_SAMPLES * 2) {
                    float x = (float)remaining / (float)RAMP_SAMPLES;
                    float rel_env = 0.5f * (1.0f - cosf(3.14159265f * x));
                    if (rel_env < env) env = rel_env;
                }

                float s1 = sinf(sfx_phase);
                float s3 = sinf(sfx_phase * 3.0f);
                float s5 = sinf(sfx_phase * 5.0f);
                float warm_wave = 0.65f * s1 + 0.25f * s3 + 0.10f * s5;

                sample += warm_wave * (sfx_amplitude * env);
                sfx_note_sample_idx++;
                produced = true;
            }

            sfx_phase += sfx_phase_step;
            if (sfx_phase >= 2.0f * 3.14159265f) {
                sfx_phase -= 2.0f * 3.14159265f;
            }
        }
    }

    if (produced) {
        *out_sample = sample;
    }
    return produced;
}
