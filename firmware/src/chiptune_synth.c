static float chiptune_phase = 0.0f;
static float chiptune_phase_step = 0.0f;

// Cosmic SFX state
static volatile int active_cosmic_sfx = -1;
static volatile size_t cosmic_sfx_step = 0;
static volatile uint32_t sfx_note_samples_left = 0;
static volatile uint32_t sfx_sound_samples_left = 0;
static volatile uint32_t sfx_note_sample_idx = 0;
static float sfx_current_freq = 0.0f;
static float sfx_amplitude = 0.0f;
static float sfx_phase = 0.0f;
static float sfx_phase_step = 0.0f;

static float calc_amp(float freq_hz) {
    return freq_hz > 0.0f ? AUDIO_PCM16_PEAK : 0.0f;
}

void chiptune_synth_init(void) {
    chiptune_synth_stop();
    chiptune_synth_stop_sfx();
}

int chiptune_synth_get_count(void) {
    return CHIPTUNE_TRACK_COUNT;
}

const char* chiptune_synth_get_name(int track_id) {
    if (track_id >= 0 && track_id < CHIPTUNE_TRACK_COUNT) {
        return CHIPTUNE_TRACKS[track_id].name;
    }
    return "UNKNOWN";
}

const chiptune_track_t* chiptune_synth_get_track(int track_id) {
    if (track_id >= 0 && track_id < CHIPTUNE_TRACK_COUNT) {
        return &CHIPTUNE_TRACKS[track_id];
    }
    return NULL;
}

void chiptune_synth_play(int track_id) {
    if (track_id >= 0 && track_id < CHIPTUNE_TRACK_COUNT) {
        chiptune_synth_stop_sfx();
        uint32_t save = save_and_disable_interrupts();
        const chiptune_track_t *trk = &CHIPTUNE_TRACKS[track_id];
        if (trk->type == TRACK_TYPE_ADPCM) {
            // ADPCM tracks are handled by audio.c streamer
            active_chiptune_track = -1;
            chiptune_step = 0;
            live_chiptune_freq = 440.0f;
            chiptune_current_freq = 0.0f;
            chiptune_note_samples_left = 0;
            chiptune_sound_samples_left = 0;
            chiptune_note_sample_idx = 0;
        } else {
            active_chiptune_track = track_id;
            chiptune_step = 0;
            if (trk->count > 0) {
                float f = trk->notes[0].freq;
                uint32_t dur = trk->notes[0].dur_ms;
                chiptune_current_freq = f;
                live_chiptune_freq = f;
                chiptune_amplitude = calc_amp(f);
                uint32_t tot = (dur * AUDIO_SAMPLE_RATE) / 1000;
                chiptune_note_samples_left = tot;
                chiptune_sound_samples_left = (f > 0.0f) ? ((tot * 94) / 100) : 0;
                chiptune_note_sample_idx = 0;
                chiptune_phase_step = (f > 0.0f) ? (f * 2.0f * 3.14159265f / (float)AUDIO_SAMPLE_RATE) : 0.0f;
            } else {
                active_chiptune_track = -1;
                chiptune_note_samples_left = 0;
                chiptune_sound_samples_left = 0;
                chiptune_note_sample_idx = 0;
            }
        }
        restore_interrupts(save);
    }
}

void chiptune_synth_stop(void) {
    uint32_t save = save_and_disable_interrupts();
    active_chiptune_track = -1;
    chiptune_step = 0;
    live_chiptune_freq = 0.0f;
    chiptune_current_freq = 0.0f;
    chiptune_note_samples_left = 0;
    chiptune_sound_samples_left = 0;
    chiptune_note_sample_idx = 0;
    chiptune_phase = 0.0f;
    chiptune_phase_step = 0.0f;
    restore_interrupts(save);
}

